def search(question, k=3, collection=None):
    if collection is None:
        collection = col
    q_vec = embed([question])[0]
    hits = collection.query(query_embeddings=[q_vec], n_results=min(k, collection.count()))
    return list(zip(hits["documents"][0], hits["distances"][0]))

