def split_sections(text):
    text = text.strip()
    if "## " in text:
        return re.split(r"\n(?=## )", text)
    return [p.strip() for p in re.split(r"\n\s*\n", text) if p.strip()]

def make_chunks(text, max_chars=500, merge=False):
    pieces = []
    for sec in split_sections(text):
        if len(sec) <= max_chars:
            pieces.append(sec)
            continue
        if sec.startswith("## "):
            heading, _, body = sec.partition("\n")
            heading += "\n"
        else:
            heading, body = "", sec
        current = ""
        for sentence in re.split(r"(?<=[.!?])\s+", body):
            if current and len(heading) + len(current) + len(sentence) > max_chars:
                pieces.append(heading + current.strip())
                current = ""
            current += sentence + " "
        if current.strip():
            pieces.append(heading + current.strip())

    if not merge:
        return pieces

    merged = []
    for p in pieces:
        if merged and len(merged[-1]) + len(p) + 2 <= max_chars:
            merged[-1] += "\n\n" + p
        else:
            merged.append(p)
    return merged

